"""Generate a fixed synthesis ROM; output is independently checked in xsim."""
import argparse
from pathlib import Path


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    lines = ["// Generated by scripts/generate_contrast_lut.py; integer half-up + saturation.",
             "function automatic [7:0] contrast_lut(input [7:0] gray);", "    case (gray)"]
    lines += [f"        8'd{i}: contrast_lut = 8'd{min(255, (255 * i + 96) // 192)};" for i in range(256)]
    lines += ["        default: contrast_lut = 8'd0;", "    endcase", "endfunction", ""]
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(lines), encoding="ascii")


if __name__ == "__main__":
    main()
